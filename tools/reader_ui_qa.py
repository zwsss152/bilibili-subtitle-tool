"""100% Tk reader checks in an isolated library, without ASR or user-file writes.

Widget events are generated by Tk; captures include only this fixture's HWND.
This does not claim physical mouse/keyboard or other display-scale acceptance.
"""
from contextlib import ExitStack
import hashlib
from pathlib import Path
import sys
import tempfile
from unittest.mock import patch

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from PIL import ImageGrab
from src.config import atomic_json, read_json
from src.paths import PROJECT_ROOT
from src.core import documents, library, reading, rename, textout, topics
from src.core.links import parse_source
from src.services import reading_service
from src.services.scheduler import Scheduler
from src.services.tasks import Page, Task
import src.ui.batch_app as module


def main():
    artifacts = PROJECT_ROOT / 'tests' / '.artifacts'
    artifacts.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='reader-ui-', dir=artifacts) as temporary, ExitStack() as stack:
        root = Path(temporary).resolve()
        assert root.is_relative_to(artifacts.resolve())
        output = root / 'output'
        for target in (module, documents, library, rename, reading_service):
            stack.enter_context(patch.object(target, 'OUTPUT_ROOT', output))
        for target in (documents, rename):
            stack.enter_context(patch.object(target, 'RECORDS_DIR', root / 'records'))
        stack.enter_context(patch.object(module, 'create_topic', lambda name: topics.create_topic(name, output)))
        stack.enter_context(patch.object(module, 'load_config', lambda: dict(topic='阅读验收', geometry='1180x820+30+30', engine='cloud')))
        stack.enter_context(patch.object(module, 'save_config', lambda **values: None))
        stack.enter_context(patch.object(module, 'Scheduler', lambda **kwargs: Scheduler(state_path=root / 'queue.json', autostart=False)))
        app = module.BatchApp(autostart=False, demo_scale=1.0)
        app.title('文字稿 · 阅读排版验收 100%')
        errors = []
        app.report_callback_exception = lambda *args: errors.append(str(args[1]))
        try:
            title = '游戏 AI：从五状态循环到行为树——完整阅读稿排版示例'
            url = 'https://www.bilibili.com/video/BV17x411w7KC?p=1'
            paragraph = ('这份稿件保留完整的讲述顺序。我们先讨论巡逻与发现目标，再讨论追击和脱战。'
                         '预算是100000元，不是10000元。Hello world。'
                         '如果条件不成立，就不能把可能发生的情况写成确定的结论。')
            segments = [dict(start=i*12, end=i*12+8, text=paragraph) for i in range(28)]
            segments.append(dict(start=340, end=349, text='最后一段：全文复制不能遗漏这句话。'))
            original, raw = textout.save_result(output / library.ORIGINAL / '阅读验收', title,
                url, 'B站', '界面样例', segments, 'fixture')
            original = Path(original)
            readable = library.reading_path(original, output)
            readable.parent.mkdir(parents=True, exist_ok=True)
            readable.write_text(f'# {title}\n来源：{url}\n整理方式：本地智能整理\n\n'
                '## 从巡逻到追击\n\n预算是100000元，不是10000元。Hello\nworld。\n\n'
                + '\n\n'.join([paragraph] * 14)
                + '\n\n## 条件、例子与结论\n\n'
                + '\n\n'.join([paragraph] * 14)
                + '\n\n最后一段：全文复制不能遗漏这句话。\n', encoding='utf-8')
            record = read_json(raw, {})
            record['reading'] = dict(status='完成', source_hash=reading.fingerprint(textout.read_document(original)))
            atomic_json(raw, record)
            hashes = {p: hashlib.sha256(p.read_bytes()).hexdigest() for p in (original, readable)}
            job = Task.create(parse_source(url), '阅读验收')
            job.title, job.status = title, '完成'
            job.pages = [Page(1, title, url, status='完成', progress=100,
                             txt=str(original.relative_to(PROJECT_ROOT)), raw=str(Path(raw).relative_to(PROJECT_ROOT)),
                             reading=str(readable.relative_to(PROJECT_ROOT)), reading_status='完成')]
            app.scheduler.jobs = [job]
            app.scheduler._persist()
            app.refresh_library()
            app.open_document(original)
            app.update()
            assert app.reader.body_font.actual('size') == 13
            assert app.reader.body_font.actual('family') in ('Microsoft YaHei', '微软雅黑', 'Microsoft YaHei UI')
            assert app.reader.cget('state') == 'disabled'
            assert app.reader.get('1.0', 'end').count(title) == 1
            assert app.reader.tag_ranges('timestamp')
            assert app.reader.tag_ranges('metadata')

            captures = PROJECT_ROOT / 'docs' / 'qa'
            captures.mkdir(exist_ok=True)

            def capture(name):
                app.update()
                def save():
                    ImageGrab.grab(window=app.winfo_id()).save(captures / name, quality=92)
                    app.quit()
                app.after(200, save)
                app.mainloop()

            assert app.cfg.get('engine') == 'cloud'
            assert not hasattr(app, 'engine_box')
            capture('cloud-desktop.jpg')
            app.settings()
            app.update()
            import tkinter as tk
            settings = next(w for w in app.winfo_children() if isinstance(w,tk.Toplevel))
            app.after(250,lambda:ImageGrab.grab(window=settings.winfo_id()).save(captures/'dual-mode-settings.jpg',quality=92))
            app.after(400,app.quit)
            app.mainloop()
            settings.destroy()

            app.copy_all()
            original_copy = app.clipboard_get()
            assert title in original_copy and url in original_copy and '[00:00]' in original_copy
            assert '最后一段：全文复制不能遗漏这句话。' in original_copy
            with patch.object(module.os, 'startfile') as opening:
                app.open_output()
                assert Path(opening.call_args.args[0]) == original.parent
            capture('reader-original.jpg')
            app.mode_var.set(library.READING)
            app.mode_box.event_generate('<<ComboboxSelected>>')
            app.update()
            visible = app.reader.get('1.0', 'end')
            assert visible.count(title) == 1 and '## ' not in visible and '[00:00]' not in visible
            assert 'Hello world。' in visible
            assert app.reader.tag_ranges('title') and app.reader.tag_ranges('heading')
            app.copy_all()
            full_copy = app.clipboard_get()
            assert title in full_copy and url in full_copy and '整理方式：本地智能整理' in full_copy
            assert '最后一段：全文复制不能遗漏这句话。' in full_copy
            assert '100000' in full_copy and '10000' in full_copy and '不是' in full_copy
            start = app.reader.search('100000', '1.0')
            app.reader.tag_add('sel', start, f'{start}+6c')
            app.copy_selection()
            assert app.clipboard_get() == '100000'
            with patch.object(module.os, 'startfile') as opening:
                app.open_output()
                assert Path(opening.call_args.args[0]) == readable.parent
            with patch.object(module.webbrowser, 'open') as opening:
                app.open_source()
                assert opening.call_args.args[0] == url
            app.reader.tag_remove('sel', '1.0', 'end')
            capture('reader-organized.jpg')

            app.reader.yview_moveto(.5)
            previous = app.reader.yview()[0]
            app.render()
            app.update()
            assert abs(app.reader.yview()[0] - previous) < .02
            app.reader.yview_moveto(0)
            app.geometry('1500x900+20+20')
            app.update()
            assert int(app.reader.cget('padx')) > 24
            assert app.reader.winfo_width() - 2*int(app.reader.cget('padx')) <= app.reader.column_width + 2
            capture('reader-wide.jpg')
            app.geometry('960x680+30+30')
            app.update()
            assert app.reader.winfo_height() > 170
            assert app.reader.xview() == (0.0, 1.0)
            assert app.reader.winfo_rooty() + app.reader.winfo_height() < app.winfo_rooty() + app.winfo_height()
            first_body = app.reader.search('预算是100000元', '1.0')
            assert app.reader.dlineinfo(first_body) is not None, 'Long title hides all body text in the narrow window'
            capture('reader-small.jpg')

            # A long metadata URL must wrap; an unheaded historical TXT must
            # retain its first sentence rather than treating it as a header.
            historical = original.parent / '历史短稿.txt'
            historical.write_text('没有标题的第一句。\n\n下一段保留100000与英文 Hello world。', encoding='utf-8')
            app.mode_var.set(library.ORIGINAL)
            app.open_document(historical)
            app.update()
            assert '没有标题的第一句。' in app.reader.get('1.0', 'end')
            app.copy_all()
            assert '没有标题的第一句。' in app.clipboard_get()
            app.mode_var.set(library.READING)
            app.mode_box.event_generate('<<ComboboxSelected>>')
            app.update()
            assert '尚未完成' in app.reader.get('1.0', 'end')
            app.copy_all()
            assert '尚未完成' in app.status_var.get()
            with patch.object(module, 'fingerprint', return_value='changed-source'):
                app.open_document(original)
                app.update()
                assert app.reader.get('1.0', 'end').count(title) == 1
                assert '尚未完成' in app.reader.get('1.0', 'end')
            long_url = 'https://www.bilibili.com/video/BV17x411w7KC?reference=' + 'a' * 500
            app.reader.show(module.parse_document(f'# 长来源样例\n来源：{long_url}\n\n正文保留100000与 Hello world。'))
            app.update()
            assert app.reader.xview() == (0.0, 1.0)
            assert long_url in app.reader.copy_text
            for path, before in hashes.items():
                assert hashlib.sha256(path.read_bytes()).hexdigest() == before
            assert not errors, errors
            print('READER UI PASS: 100%, long/short TXT, headings, timestamps, both copy modes, folders/source, scroll, wide/narrow, pending, unchanged bytes', flush=True)
        finally:
            app.scheduler.shutdown()
            app.destroy()


if __name__ == '__main__':
    main()

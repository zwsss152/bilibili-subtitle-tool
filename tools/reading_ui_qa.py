"""Exercise real Tk controls in an isolated library, with visible render captures.

Events are generated by Tk, not physical mouse/keyboard injection. This does not
claim OS display-scale or computer-use click acceptance.
"""
from pathlib import Path
import sys
import tempfile
import tkinter as tk
from unittest.mock import patch
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from PIL import ImageGrab
from src.paths import PROJECT_ROOT
from src.core import documents, library, reading, rename, textout, topics
from src.core.links import parse_source
from src.services import reading_service
from src.services.scheduler import Scheduler
from src.services.tasks import Task, Page
import src.ui.batch_app as module


def main():
    artifacts=PROJECT_ROOT/'tests'/'.artifacts'
    artifacts.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='reading-ui-',dir=artifacts) as temporary:
        root=Path(temporary).resolve()
        assert root.is_relative_to(artifacts.resolve())
        output=root/'output'
        for target in (module,documents,library,rename,reading_service):
            target.OUTPUT_ROOT=output
        documents.RECORDS_DIR=rename.RECORDS_DIR=root/'records'
        module.create_topic=lambda name:topics.create_topic(name,output)
        module.load_config=lambda:dict(topic='验收主题',geometry='1180x820+30+30')
        module.save_config=lambda **values:None
        module.Scheduler=lambda **kwargs:Scheduler(state_path=root/'queue.json',autostart=False)
        app=module.BatchApp(autostart=False)
        app._save_settings=lambda:None
        errors=[]
        app.report_callback_exception=lambda *args:errors.append(str(args[1]))
        app.title('文字稿 · 双稿件验收')
        app.geometry('1180x820+30+30')
        source=[dict(start=0,end=5,text='我们这个预算是100000元，不是10000元。Hello world。这是一份用于界面验收的稿件。'),
                dict(start=12,end=20,text='可能会先讨论主题，再按顺序整理段落。所有事实和例子都需要保留。')]
        txt,raw=textout.save_result(output/library.ORIGINAL/'验收主题','示例稿件',
            'https://www.bilibili.com/video/BV17x411w7KC','B站','验收',source,'fixture')
        job=Task.create(parse_source('BV17x411w7KC'),'验收主题')
        job.title,job.status='示例稿件','完成'
        job.pages=[Page(1,'示例稿件',job.source_url,status='完成',progress=100,
            txt=str(Path(txt).relative_to(PROJECT_ROOT)),raw=str(Path(raw).relative_to(PROJECT_ROOT)))]
        app.scheduler.jobs=[job]
        class Editor:
            def start(self,cancel=None):pass
            def generate(self,system,content,schema,cancel=None):
                import json
                data=json.loads(content)
                if 'units' in data:return {'units':[{'id':u['id'],'heading':'预算与整理原则' if i==0 else '', 'text':u['text']} for i,u in enumerate(data['units'])]}
                return {'checks':[{'id':u['id'],'accepted':True,'reason':'保留信息'} for u in data]}
        app.scheduler.reading_service.enqueue((job.jid,1))
        with patch.object(reading,'enabled',return_value=True),patch.object(reading_service,'resources_ready',return_value=True):
            while app.scheduler.reading_service.has_work():app.scheduler.reading_service.step(Editor())
        app.scheduler._persist()
        app.refresh_library()
        app.open_document(txt)
        app.update()
        assert tuple(app.mode_box['values'])==(library.ORIGINAL,library.READING)
        assert len(app.documents)==1
        assert '[00:00]' in app.reader.get('1.0','end')
        captures=PROJECT_ROOT/'docs'/'qa'
        captures.mkdir(exist_ok=True)
        def capture(name):
            app.update()
            # Capture our own HWND rather than the desktop; other user windows
            # may occlude this fixture and must never enter the QA artifacts.
            app.after(250,lambda:ImageGrab.grab(window=app.winfo_id()).save(captures/name,quality=92))
            app.after(400,app.quit)
            app.mainloop()
        capture('reading-original.jpg')
        app.mode_var.set(library.READING)
        app.mode_box.event_generate('<<ComboboxSelected>>')
        app.update()
        assert '预算与整理原则' in app.reader.get('1.0','end')
        assert '[00:00]' not in app.reader.get('1.0','end')
        app.copy_all()
        assert 'Hello world' in app.clipboard_get()
        with patch.object(module.os,'startfile') as opening:
            app.open_output()
            assert Path(opening.call_args.args[0])==Path(PROJECT_ROOT/job.pages[0].reading).parent
        capture('reading-organized.jpg')
        mapping=app.scheduler.rename_transcript(job.jid,'改名后稿件')
        app.open_document(PROJECT_ROOT/mapping[job.pages[0].txt] if job.pages[0].txt in mapping else PROJECT_ROOT/job.pages[0].txt)
        app.refresh_library()
        assert '改名后稿件' in app.reader.get('1.0','end')
        assert len(app.documents)==1
        app.geometry('960x680+30+30')
        capture('reading-small.jpg')
        assert not errors,errors
        app.scheduler.shutdown()
        app.destroy()
        print('TK UI PASS: two variants, one list entry, copy, folders, paired rename, resize',flush=True)


if __name__=='__main__':main()
